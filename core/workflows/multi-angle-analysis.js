export const meta = {
  name: 'multi-angle-analysis',
  description: 'تحليل متوازي من 3 زوايا: تقنية، أمنية، تجربة مستخدم/أداء — ثم تركيب النتائج',
  phases: [
    { title: 'تحليل متوازي', detail: '3 زوايا تحليل متزامنة' },
    { title: 'مقارنة', detail: 'مقارنة النتائج واستخراج التناقضات' },
    { title: 'تقرير', detail: 'تجميع التقرير النهائي' }
  ]
}

const TARGET = typeof args === 'string' ? args : (process.env.TARGET || '.')

phase('تحليل متوازي')
const [technical, security, uxPerf] = await parallel([
  () => agent(`حلل الكود من الزاوية التقنية البحتة:
- هل البنية المعمارية سليمة؟
- هل هناك مشاكل في types/interfaces؟
- هل التبعيات (dependencies) منطقية؟
- هل هناك تكرار في الكود (DRY violations)؟
- هل التعامل مع الأخطاء كافٍ؟

الكود: ${TARGET}`, { label: 'زاوية تقنية' }),

  () => agent(`حلل الكود من الزاوية الأمنية:
- هل هناك ثغرات حقن (SQL, XSS, Command Injection)؟
- هل البيانات الحساسة مشفرة/محمية؟
- هل المصادقة والصلاحيات سليمة؟
- هل هناك أسرار أو مفاتيح مكشوفة؟
- هل التعامل مع المدخلات الخارجية آمن؟

الكود: ${TARGET}`, { label: 'زاوية أمنية' }),

  () => agent(`حلل الكود من زاوية تجربة المستخدم والأداء:
- هل الأداء مقبول (سرعة التحميل، استهلاك الذاكرة)؟
- هل الكود يؤثر سلباً على تجربة المستخدم؟
- هل هناك تحسينات ممكنة للأداء؟
- هل accessibility مدعومة؟
- هل هناك معالجة للأخطاء تراعي المستخدم؟

الكود: ${TARGET}`, { label: 'زاوية UX/أداء' })
])

phase('مقارنة')
const comparison = await agent(`قارن نتائج التحليلات الثلاثة.
استخرج:
1. النقاط المتقاطعة (ذكرت في أكثر من تحليل) — هذه هي الأهم
2. التناقضات (اختلاف في التقييم بين الزوايا)
3. الثغرات (جوانب لم تغطها أي من الزوايا)

النتائج:
- التقنية: ${technical || 'غير متوفرة'}
- الأمنية: ${security || 'غير متوفرة'}
- UX/أداء: ${uxPerf || 'غير متوفرة'}`, { label: 'مقارنة وتقاطع' })

phase('تقرير')
log('# 🔬 تحليل متعدد الزوايا')
log(`**الهدف**: ${TARGET}`)
log('')
log('## 🖥️ الزاوية التقنية')
log(technical || 'لا توجد نتائج')
log('')
log('## 🔒 الزاوية الأمنية')
log(security || 'لا توجد نتائج')
log('')
log('## ⚡ زاوية الأداء وتجربة المستخدم')
log(uxPerf || 'لا توجد نتائج')
log('')
log('## 🔀 التقاطعات والتناقضات')
log(comparison || 'لا توجد مقارنة')
log('')
log('---')
log('🔬 اكتمل التحليل المتعدد الزوايا')

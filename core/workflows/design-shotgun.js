export const meta = {
  name: 'design-shotgun',
  description: 'يولّد 3 اتجاهات تصميم متوازية، يقارنها بمعايير محددة، ويدمج الأقوى مع أفضل عناصر البقية — ثم يخرج بتصميم نهائي واحد',
  phases: [
    { title: 'تحليل', detail: 'تحليل سياق المشروع وتحديد 3 أو 4 اتجاهات' },
    { title: 'توليد', detail: 'توليد 3 اتجاهات تصميم متوازية' },
    { title: 'مقارنة', detail: 'تقييم الاتجاهات بمعايير محددة واختيار الأقوى' },
    { title: 'دمج', detail: 'دمج الفائز مع أفضل عناصر الاتجاهين الآخرين' }
  ],
  whenToUse: 'استخدم عند بداية أي مهمة فيها واجهة جديدة — موقع، لوحة تحكم، صفحة هبوط، مكونات — لتوليد اتجاهات متعددة واختيار الأقوى بدلاً من البدء باتجاه واحد'
}

// ─── Phase 1: تحليل ───────────────────────────────────────────────
phase('تحليل')

const BRIEF = typeof args === 'string' ? args : (process.env.BRIEF || null)
const TARGET = typeof args === 'string' ? args : 'المشروع الحالي'

const context = await agent(`حلل المشروع لتحديد:
1. نوع المشروع: brand (موقع تسويقي، صفحة هبوط، محفظة) أم product (لوحة تحكم، تطبيق، أداة)؟
2. هل المشروع ترفيهي/تعليمي/ألعاب؟ (هذا يحدد是否需要 اتجاه creative رابع)
3. ما هي الكلمات الثلاث التي تصف شخصية العلامة التجارية؟ (كلمات ملموسة، ليست "حديث" أو "أنيق")
4. ما المنافسون المباشرون وأسلوبهم البصري؟
5. هل هناك نظام تصميم أو tokens موجود يجب البناء عليه؟

${BRIEF ? `وصف المشروع من المستخدم: ${BRIEF}` : 'افحص الملفات المحيطة و PRODUCT.md إن وُجد'}
الكود: ${TARGET}`, { label: 'تحليل السياق' })

const needsCreative = context && (context.includes('ترفيه') || context.includes('ألعاب') || context.includes('تعليم') || context.includes('أطفال'))
const DIRECTION_COUNT = needsCreative ? 4 : 3
log(`الاتجاهات المطلوبة: ${DIRECTION_COUNT} ${needsCreative ? '(متضمن creative)' : '(المعيارية الثلاثة)'}`)

// ─── Phase 2: توليد ───────────────────────────────────────────────
phase('توليد')

const prompts = [
  {
    key: 'minimal',
    label: 'اتجاه minimal',
    prompt: `صمم واجهة ${TARGET} بأسلوب minimal (بساطة قصوى):

**الشخصية**: هادئ، منضبط، مركز على المحتوى — لا عناصر زائدة.
**الفراغ**: مساحات بيضاء واسعة، هامش كبير، كثافة منخفضة.
**اللون**: لون واحد مهيمن + تدرجات محايدة (رمادي، أبيض، أسود). لا أكثر من 3 ألوان.
**الخط**: عائلة واحدة sans-serif نظيفة بتباين أوزان. لا display fonts.
**الشبكة**: عمود واحد أو عمودين كحد أقصى. تناظر واستقامة.
**الحركة**: خفيفة جداً، fade فقط. لا choreography معقدة.

المخرجات المطلوبة:
1. وصف palette الألوان (primary, background, surface, ink, muted — بصيغة OKLCH أو hex)
2. اختيار خط واحد مع تبرير
3. هيكل التخطيط العام (wireframe وصفي)
4. 3 قرارات تصميمية رئيسية مع تبرير كل منها
5. كود CSS tokens جاهز (custom properties)`
  },
  {
    key: 'modern',
    label: 'اتجاه modern/bold',
    prompt: `صمم واجهة ${TARGET} بأسلوب modern/bold (جريء ومعاصر):

**الشخصية**: واثق، تقني، طموح — لا تردد.
**اللون**: تباين عالي، خلفية داكنة أو gradients جريئة. لون accent نيون أو مشبع.
**الخط**: geometric sans-serif للعناوين، خط عملي للنص. تباين حجم واضح (≥1.33).
**التخطيط**: asymmetric grids، كسر التناظر المتعمد، زوايا حادة.
**الحركة**: نشطة — hover effects، scroll-triggered animations، page transitions.
**التفاصيل**: glassmorphism أو noise textures أو grid backgrounds — بجرعات محسوبة.

المخرجات المطلوبة:
1. وصف palette الألوان (primary, background, surface, ink, muted — بصيغة OKLCH أو hex)
2. اختيار الخطوط مع تبرير
3. هيكل التخطيط العام (wireframe وصفي)
4. 3 قرارات تصميمية رئيسية مع تبرير كل منها
5. كود CSS tokens جاهز (custom properties)`
  },
  {
    key: 'elegant',
    label: 'اتجاه elegant/luxury',
    prompt: `صمم واجهة ${TARGET} بأسلوب elegant/luxury (فاخر وراقي):

**الشخصية**: راقي، خالد، مصقول — لا صراخ.
**اللون**: لوحة داكنة غنية (deep navy, charcoal, warm black) + لمسات ذهبية أو نحاسية. تدرجات ناعمة جداً.
**الخط**: serif display للعناوين + sans-serif نظيف للنص. تباين بين الأناقة والوضوح.
**التخطيط**: مساحات واسعة، margins كبيرة، تناظر أنيق. صور كبيرة بجودة عالية.
**التفاصيل**: حدود رفيعة، فواصل ذهبية، تدرجات خلفية شفافة، زخرفة محسوبة.
**الحركة**: بطيئة وأنيقة — 400-600ms transitions. ظهور تدريجي. parallax ناعم.

المخرجات المطلوبة:
1. وصف palette الألوان (primary, background, surface, ink, muted — بصيغة OKLCH أو hex)
2. اختيار الخطوط مع تبرير
3. هيكل التخطيط العام (wireframe وصفي)
4. 3 قرارات تصميمية رئيسية مع تبرير كل منها
5. كود CSS tokens جاهز (custom properties)`
  }
]

if (needsCreative) {
  prompts.push({
    key: 'creative',
    label: 'اتجاه creative/playful',
    prompt: `صمم واجهة ${TARGET} بأسلوب creative/playful (إبداعي ومرح):

**الشخصية**: لعوب، خيالي، مفاجئ — لا ملل.
**اللون**: لوحة واسعة (4-6 ألوان)، ألوان زاهية ومشبعة، تباين مرح. gradients ملونة.
**الخط**: display font فريد للعناوين (rounded, handwritten, أو experimental) + خط مقروء للنص.
**التخطيط**: تخطيط غير متوقع، عناصر متداخلة، زوايا دائرية، أشكال عضوية.
**الرسوم**: illustrations مرسومة يدوياً أو 3D، شخصيات، رموز تعبيرية، عناصر تفاعلية.
**الحركة**: مرحة وسريعة — bouncy transitions، micro-interactions، hover states مبالغ فيها.

المخرجات المطلوبة:
1. وصف palette الألوان (primary, background, surface, ink, muted — بصيغة OKLCH أو hex)
2. اختيار الخطوط مع تبرير
3. هيكل التخطيط العام (wireframe وصفي)
4. 3 قرارات تصميمية رئيسية مع تبرير كل منها
5. كود CSS tokens جاهز (custom properties)`
  })
}

// توليد كل الاتجاهات متوازياً
const directionsRaw = await parallel(
  prompts.map(p => () => agent(p.prompt, { label: p.label }))
)

const directions = prompts.map((p, i) => ({
  key: p.key,
  label: p.label,
  content: directionsRaw[i] || '⚠️ فشل التوليد'
}))

// ─── Phase 3: مقارنة ──────────────────────────────────────────────
phase('مقارنة')

const comparison = await agent(`قارن بين ${DIRECTION_COUNT} اتجاهات التصميم التالية لمشروع "${TARGET}".

**سياق المشروع:**
${context || 'مشروع عام — لا سياق إضافي'}

**معايير التقييم (كل معيار من 10):**
1. ملاءمة هوية المشروع — هل يعكس شخصية العلامة؟
2. سهولة الاستخدام والوضوح — هل الواجهة مفهومة من أول نظرة؟
3. التميز عن المنافسين — هل يختلف بشكل إيجابي؟
4. قابلية التنفيذ — هل يمكن بناؤه ضمن الوقت/الميزانية المعقولة؟
5. مرونة التوسع — هل يتحمل صفحات ومكونات إضافية؟

**الاتجاهات:**
${directions.map((d, i) => `### ${i + 1}. ${d.label} (${d.key})\n${d.content}\n---\n`).join('\n')}

أخرج:
1. **جدول تقييم**: صفوف = الاتجاهات، أعمدة = المعايير الخمسة، مع درجة لكل خلية
2. **الترتيب النهائي**: من الأول إلى الأخير مع مجموع الدرجات
3. **نقاط قوة كل اتجاه** (حتى الخاسر — قد نأخذ منه عناصر)
4. **نقاط ضعف الفائز** (ما يحتاج تحسينه)`, { label: 'مقارنة وتقييم' })

// ─── Phase 4: دمج ─────────────────────────────────────────────────
phase('دمج')

const winner = await agent(`بناءً على المقارنة السابقة، اختر الاتجاه الفائز وادمجه مع أفضل عناصر الاتجاهين الآخرين.

**نتيجة المقارنة:**
${comparison || 'لا توجد مقارنة'}

**الاتجاهات الكاملة:**
${directions.map((d, i) => `### ${i + 1}. ${d.label} (${d.key})\n${d.content}\n---\n`).join('\n')}

**المطلوب — تقرير تصميم نهائي واحد:**

1. **الاتجاه الفائز**: أي اتجاه اختير ولماذا
2. **العناصر المدمجة**: ماذا أُخذ من كل اتجاه خاسر ولماذا
3. **الـ palette النهائي**: الألوان المختارة بصيغة OKLCH و hex
4. **الخطوط النهائية**: العائلة/العائلات المختارة مع تبرير
5. **قرارات التصميم الرئيسية**: 5 قرارات مع تبرير كل منها
6. **CSS tokens نهائية**: custom properties كاملة جاهزة للاستخدام
7. **نظام spacing**: مقياس المسافات (4px base أو 8px base)
8. **نظام الظلال**: مستويات elevation (0-4)
9. **نظام الزوايا**: قيم border-radius
10. **محظورات**: ما يجب تجنبه في التنفيذ

هذا التقرير هو المرجع الوحيد الذي سيبني عليه التنفيذ. لا تترك غموضاً.`, { label: 'دمج وتحسين' })

// ─── الخرج النهائي ─────────────────────────────────────────────────
log('# 🎯 Design Shotgun — التصميم النهائي')
log(`**المشروع**: ${TARGET}`)
log(`**عدد الاتجاهات**: ${DIRECTION_COUNT}`)
log('')

if (needsCreative) {
  log('> ⚠️ أُضيف اتجاه creative لأن المشروع ترفيهي/تعليمي/ألعاب')
}

log('## 📊 نتائج المقارنة')
log(comparison || 'لا توجد نتائج')
log('')
log('## 🏆 التصميم النهائي المدمج')
log(winner || '⚠️ فشل الدمج')
log('')
log('---')
log('🎯 اكتمل Design Shotgun — استخدم التصميم النهائي أعلاه لبدء التنفيذ')

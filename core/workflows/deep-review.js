export const meta = {
  name: "deep-review",
  description:
    "مراجعة عميقة متعددة المراحل: فحص → تفكير ← code-reviewer ← اقتراحات قابلة للتنفيذ",
  phases: [
    { title: "فحص", detail: "جمع السياق والتغييرات" },
    { title: "تفكير عميق", detail: "تحليل متعدد الزوايا" },
    { title: "مراجعة", detail: "code-reviewer بمستوى جهد قابل للتخصيص" },
    { title: "تقرير", detail: "تجميع النتائج والاقتراحات" },
  ],
};

const TARGET = typeof args === "string" ? args : process.env.TARGET || ".";

phase("فحص");
const context = await agent(
  `اجمع معلومات عن الكود المستهدف: ${TARGET}.
شغّل:
- git diff --stat
- git log --oneline -5
- اذكر الملفات المعدلة وأحجامها
- حدد المناطق الأكثر خطورة`,
  { label: "جمع السياق" },
);

phase("تفكير عميق");
const analysis = await agent(
  `حلل الكود من 3 زوايا مختلفة:

الزاوية 1 — المنطق والهيكلة: هل التصميم سليم؟ هل هناك تكرار؟ هل الفصل بين المكونات واضح؟
الزاوية 2 — الأداء والأمان: هل هناك استعلامات N+1؟ هل هناك ثغرات حقن؟ هل البيانات محمية؟
الزاوية 3 — القابلية للتطوير: هل الكود سهل التعديل؟ هل هناك اختبارات؟ هل التوثيق كافٍ؟

الكود المستهدف: ${TARGET}
السياق: ${context || "غير متوفر"}`,
  { label: "تحليل متعدد الزوايا" },
);

phase("مراجعة");
const effort = (typeof args === "object" && args?.effort) || "high";
const review = await agent(
  `الهدف: ${TARGET}
مستوى الجهد: ${effort}

--- سياق التغيير ---
${context || "غير متوفر"}

--- تحليل سابق ---
${analysis || "غير متوفر"}

راجع الكود المستهدف. استخدم نتائج التحليل السابق لتركيز المراجعة على المناطق الأكثر خطورة.`,
  { label: "مراجعة code-reviewer", agentType: "code-reviewer" },
);

phase("تقرير");
const suggestions = await agent(
  `بناءً على المراجعة، قدم 3-5 اقتراحات محددة وقابلة للتنفيذ.
كل اقتراح يجب أن يتضمن:
- وصف المشكلة
- الخطوات المطلوبة
- الملفات المتأثرة
- درجة الأولوية (حرج/عالي/متوسط/منخفض)

نتائج المراجعة: ${review || "غير متوفرة"}
السياق الكامل: ${context || "غير متوفر"}`,
  { label: "اقتراحات" },
);

log("# 📊 تقرير المراجعة العميقة");
log(`**الهدف**: ${TARGET}`);
log("");
log("## 🔍 السياق");
log(context || "لا يوجد سياق متوفر");
log("");
log("## 🧠 التحليل العميق");
log(analysis || "لا يوجد تحليل متوفر");
log("");
log("## 📋 مراجعة code-reviewer");
log(review || "لا توجد مراجعة متوفرة");
log("");
log("## 💡 الاقتراحات");
log(suggestions || "لا توجد اقتراحات");
log("");
log("---");
log("✨ تمت المراجعة العميقة بنجاح");
